#!/usr/bin/env python3
"""Render the generated block of doc-mk/Evaluation/DP1/benchmark.md from DP1/sim/scenarios.py.

Discovers public zero-arg callables in scenarios.py named `scenarios` or `*_benchmark`
that return a list of Scenario dataclasses; one table per set. Stdlib only.
Usage: python3 gen_dp1_benchmark_doc.py [--check]
"""
import dataclasses, importlib, inspect, sys
from pathlib import Path

EVAL = Path(__file__).resolve().parents[1]
SIM = EVAL / "DP1" / "sim"
DOC = EVAL / "DP1" / "benchmark.md"
BEGIN, END = "<!-- BEGIN GENERATED -->", "<!-- END GENERATED -->"

TITLES = {
    "common_benchmark": "Common Benchmark realization (cb_*)",
    "scenarios": "DP1 Stress Benchmark",
}
ORDER = ["common_benchmark", "scenarios"]
DEFAULTS_HIDE = {"size_scale": 1.0, "horizon_s": 180, "misclass_rate": 0.0, "capacity_mult": 1.0,
                 "hbm_bw_mult": 1.0, "host_bw_mult": 1.0, "hbm_capacity_mult": 1.0}


def discover(mod):
    found = []
    for n, f in vars(mod).items():
        if n.startswith("_") or not callable(f) or inspect.isclass(f):
            continue
        if not (n == "scenarios" or n.endswith("_benchmark")):
            continue
        if getattr(f, "__module__", None) != mod.__name__:
            continue
        try:
            if any(p.default is p.empty and p.kind in (p.POSITIONAL_ONLY, p.POSITIONAL_OR_KEYWORD)
                   for p in inspect.signature(f).parameters.values()):
                continue
            res = f()
        except Exception as e:  # tolerate half-edited code
            found.append((n, None, f"{type(e).__name__}: {e}"))
            continue
        if isinstance(res, list) and res and dataclasses.is_dataclass(res[0]):
            found.append((n, res, ""))
    key = lambda t: (ORDER.index(t[0]) if t[0] in ORDER else len(ORDER), t[0])
    return sorted(found, key=key)


def fmt_ctx(n):
    return f"{n//1024}K" if n % 1024 == 0 and n >= 1024 else str(n)


def fmt_mix(d):
    return ", ".join(f"{k}:{v:g}" for k, v in d.items())


def knobs(sc):
    out = []
    for k, dv in DEFAULTS_HIDE.items():
        v = getattr(sc, k, dv)
        if v != dv:
            out.append(f"{k}={v:g}")
    return "; ".join(out) or "-"


def esc(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def render():
    sys.path.insert(0, str(SIM))
    mod = importlib.import_module("scenarios")
    sets = discover(mod)
    known = {"name", "description", "data_mix", "context_tokens", "output_tokens", "batch_size", "object_count",
             "demand_scale", "phase", "disabled_tiers", "target_tiers", *DEFAULTS_HIDE}
    L = ["> Generated by `doc-mk/Evaluation/tools/gen_dp1_benchmark_doc.py` from `DP1/sim/scenarios.py`. "
         "Do not edit by hand.", "",
         "Knob column lists only non-default knobs (defaults: size_scale=1, horizon_s=180, misclass_rate=0, "
         "capacity_mult=1, hbm_bw_mult=1, host_bw_mult=1, hbm_capacity_mult=1). "
         "Other non-default fields (e.g. `rag_index_total_gib`, `latency_sensitivity_override`, or fields added later) "
         "appear in the Extra column.", ""]
    L += ["| Benchmark set | Function | Scenarios |", "|---|---|---|"]
    for n, res, err in sets:
        L.append(f"| {TITLES.get(n, n)} | `scenarios.{n}()` | {len(res) if res is not None else 'ERROR'} |")
    L.append("")
    for n, res, err in sets:
        L += [f"## G.{TITLES.get(n, n)}", ""]
        if res is None:
            L += [f"> ERROR while calling `{n}()`: {err}", ""]
            continue
        extra_names = [f.name for f in dataclasses.fields(res[0]) if f.name not in known]
        head = ["#", "name", "data mix", "ctx", "out", "batch", "objs", "demand", "phase", "knobs",
                "disabled tiers", "extra", "description"]
        L += ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
        for i, sc in enumerate(res, 1):
            ex = []
            for f in dataclasses.fields(sc):
                if f.name in extra_names:
                    v = getattr(sc, f.name)
                    if v not in (None, (), 0, 0.0, "") and v != f.default:
                        ex.append(f"{f.name}={v}")
            L.append("| " + " | ".join(esc(x) for x in [
                i, f"`{sc.name}`", fmt_mix(sc.data_mix), fmt_ctx(sc.context_tokens), sc.output_tokens,
                sc.batch_size, sc.object_count, f"{sc.demand_scale:g}", sc.phase or "-", knobs(sc),
                ", ".join(sc.disabled_tiers) or "-", "; ".join(ex) or "-", sc.description]) + " |")
        L.append("")
    return "\n".join(L).rstrip()


def main():
    block = f"{BEGIN}\n{render()}\n{END}"
    if not DOC.exists():
        print(block); return
    txt = DOC.read_text()
    if BEGIN not in txt or END not in txt:
        sys.exit(f"markers not found in {DOC}")
    new = txt[:txt.index(BEGIN)] + block + txt[txt.index(END) + len(END):]
    if "--check" in sys.argv:
        sys.exit(0 if new == txt else 1)
    DOC.write_text(new)
    print(f"updated {DOC}")


if __name__ == "__main__":
    main()
