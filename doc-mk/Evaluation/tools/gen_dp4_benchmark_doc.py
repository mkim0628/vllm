#!/usr/bin/env python3
"""Render doc-mk/Evaluation/DP4/benchmark.md from DP4/sim/scenarios.py (single source) and DP4/sim/configs/cluster_dp4.json.

One line per scenario: name | what it is (<= 60 chars, `Scenario.brief`) | As-Is weakness exposed (`Scenario.exposes`) | key parameters.
The whole file is generated; static prose below lives in this script, numbers come from scenarios.py / cluster_dp4.json.
Deterministic (no timestamps). Stdlib only.

Usage: python3 gen_dp4_benchmark_doc.py [--check]      (writes DP4/benchmark.md; --check exits 1 if the file would change)
"""
from __future__ import annotations

import importlib
import json
import sys
from pathlib import Path

EVAL = Path(__file__).resolve().parents[1]
SIM = EVAL / "DP4" / "sim"
DOC = EVAL / "DP4" / "benchmark.md"
CFG = SIM / "configs" / "cluster_dp4.json"


def esc(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def cfg_val(name):
    return json.loads(CFG.read_text())["params"][name]["value"]


def knob_params(sc, defaults):
    """Compact key parameters of one scenario (only what differs from the defaults, plus topology)."""
    k = sc.resolved()
    p = [f"P{k['n_p']}+D{k['n_d']}"]
    if (k["in_tokens"], k["out_tokens"]) != (defaults["in_tokens"], defaults["out_tokens"]):
        p.append(f"in {k['in_tokens']}/out {k['out_tokens']}")
    else:
        p.append(f"{k['in_tokens'] // 1024}K/{k['out_tokens']}")
    if k["bg0"] or k["bg1"]:
        p.append(f"bg {k['bg0']:g}" if k["bg0"] == k["bg1"] else f"bg {k['bg0']:g}→{k['bg1']:g}")
    else:
        p.append("bg 0")
    if k["kv_share"] != 1.0:
        p.append(f"KV {k['kv_share'] * 100:.0f}% mix")
    if k["turns"] > 1:
        p.append(f"turns {k['turns']} reuse {'on' if k['reuse'] else 'off'}")
    if k["hot"]:
        p.append(f"hot prefix {cfg_val('shared_prefix_frac') * 100:.0f}% x {cfg_val('shared_prefix_tokens')} tok")
    if k["pool_occ"]:
        p.append(f"pool occ {k['pool_occ']:g}")
    for key, lab in (("block_tokens", "block"), ("lock_stripes", "S"), ("server_threads", "threads")):
        if k[key] is not None:
            p.append(f"{lab} {k[key]}")
    if k["fail"]:
        p.append(f"fail {k['fail']}")
    if k["reference"]:
        p.append("reference row")
    if sc.variants:
        p.append("variants " + "/".join(s for s, _ in sc.variants))
    return ", ".join(p)


def render():
    sys.path.insert(0, str(SIM))
    mod = importlib.import_module("scenarios")
    cb, dp = mod.common_benchmark(), mod.dp4_benchmark()
    defaults = mod.DEFAULT_KNOBS
    rows_cb = sum(len(s.rows()) for s in cb)
    rows_dp = sum(len(s.rows()) for s in dp)
    L = []
    L += ["# DP4 Benchmark (DP4 맞춤형)", "",
          "> Generated by `doc-mk/Evaluation/tools/gen_dp4_benchmark_doc.py` from `DP4/sim/scenarios.py` (`brief`, `exposes`, knobs) and "
          "`DP4/sim/configs/cluster_dp4.json`. Do not edit by hand. 단일 소스는 `scenarios.py`이며 상세 파라미터는 코드와 `results/data/`를 본다.",
          ">",
          "> 대상: **DP4 — 비일관 CXL 공유 메모리의 KV·메타데이터 일관성 구조 (C1 중앙 직렬화 vs C2 분산 락)**. 최종 결과 = **Common Benchmark + 이 문서의 DP4 전용 benchmark**.",
          "> 공통 시나리오 CB-1~3의 정의는 [`../common-benchmark.md`](../common-benchmark.md) 2.1장, 이 DP에서의 실현은 아래 2장. 방법은 [`simulation-plan.md`](simulation-plan.md) §6.",
          "", "# 1. 구성", "",
          "| Set | 시나리오 수 (결과 행 수) | 목적 |", "|---|---|---|",
          f"| Common (CB-1~3) | {len(cb)} ({rows_cb}) | 공통 QA1~QA3 별점 (공통 별점은 이 set에서만 산출) |",
          f"| DP4-specific (D4-n) | {len(dp)} ({rows_dp}, 변종 행 포함; `d4_node_scale_n2`는 Scaling Efficiency 기준 행) | control plane 포화, scalability, reuse, 장애 - diagnostic, QA4 근거 |",
          "", "고정: Llama-3.1-70B BF16, 8K in / 256 out, batch 32, SLO TTFT P99 <= 2 s, TPOT P99 <= 50 ms, baseline prefix reuse 통제. "
          "시스템은 SYS-H100, SYS-B200 (통합, 시나리오 x 시스템 쌍이 집계 단위). seeds 11 23 37 53 71, load sweep x0.5/1.0/1.5/2.0 (peak가 grid 끝이면 확장).", ""]
    L += ["# 2. Common Benchmark 실현 (압박 = 링크·풀 background load)", "",
          "압박의 의미: 이 DP에서는 메모리 용량이 아니라 **서버 간 KV 이동 경로(링크/풀)의 경합**이다. background load는 노드 egress/ingress 링크와 풀 aggregate에 "
          "`1 - bg(t)`를 곱한다(RDMA NIC와 CXL 어댑터 모두). bg 수치는 ASSUMED이며 결과를 본 뒤 바꾸지 않는다.", "",
          "| ID | 시나리오 | 무엇인가 | 드러내는 As-Is 약점 | 핵심 파라미터 |", "|---|---|---|---|---|"]
    for sc in cb:
        L.append("| " + " | ".join(esc(x) for x in [sc.cb_id, f"`{sc.name}`", sc.brief, sc.exposes, knob_params(sc, defaults)]) + " |")
    L += ["", "# 3. Common Reference Baseline", "",
          "| 항목 | 내용 |", "|---|---|",
          "| Baseline 구조 | **Baseline-RDMA**: CXL 풀 없음. P→D RDMA 점대점 KV 전송 + 중앙 위치 인덱스(이벤트 push). 노드 간 prefix 공유 없음 |",
          "| 구현 | `DP4/sim/arms.py` (Baseline arm), data plane은 `DP4/sim/simulator.py`. 계산 물리(`prefill_s`, `decode_step_s`)는 `DP1/sim/model.py`를 import해 재사용(수정 안 함) |",
          "| 사용 SYS | SYS-H100, SYS-B200 (통합). Baseline과 후보가 같은 SYS, 같은 trace(seed 쌍) |",
          "| T_ref | Baseline-RDMA의 Max SLO Goodput (output tok/s), 시나리오·시스템 쌍별 |",
          f"| 강한 baseline | η_rdma {cfg_val('eta_rdma'):g}(ASSUMED), NIC {cfg_val('nic_bw_Bps') / 1e9:g} GB/s, layer 단위 연속 블록 전송, fragmentation 페널티 없음, 중앙 인덱스 조회 {cfg_val('index_lookup_us'):g} us. "
          "약한 baseline 변형(작은 블록 비효율)은 민감도 행으로만 보고하고 별점에 쓰지 않는다 |", ""]
    L += ["# 4. DP4-specific 시나리오 (한 줄씩)", "",
          "| 시나리오 | 무엇인가 | 드러내는 As-Is 약점 | 핵심 파라미터 |", "|---|---|---|---|"]
    for sc in dp:
        L.append("| " + " | ".join(esc(x) for x in [f"`{sc.name}`", sc.brief, sc.exposes, knob_params(sc, defaults)]) + " |")
    L += ["", "DP4-specific 행은 background 0(control plane 분리)이며 별점 산출에 쓰지 않는다(diagnostic, QA4 근거). 변종(`[restart]`, `[node_loss]`, `[as_published]`, `[lease]`)은 각각 별도 결과 행이다.", "",
          "# 5. fit 분류 규칙", "",
          "comparison-valid / infeasible / saturated (SKILL §4, 공통 문서 §4). saturated는 이득 근거가 아니다. 분류는 결과를 보기 전 SLO 기준으로 하며 `qa_eval.py`가 자동 부여한다(`label_scenarios`).", "",
          "# 6. 모델링하지 않는 시나리오", "",
          "CXL 풀 장치 장애·오류, 스위치 혼잡(집계 BW 상한만), 다중 테넌트 격리(문헌에서도 공백), KV 외 객체(LoRA/MoE/Agent/Tool)별 접근 패턴의 차이(CB-3은 풀 트래픽·객체 수 비율만 반영), "
          "균일 분포 접근 전용 시나리오, 실제 trace.", ""]
    return "\n".join(L).rstrip() + "\n"


def main():
    new = render()
    if "--check" in sys.argv:
        sys.exit(0 if DOC.exists() and DOC.read_text() == new else 1)
    DOC.write_text(new)
    print(f"wrote {DOC}")


if __name__ == "__main__":
    main()
