"""Markdown tables from results/data/sensitivity/summary.json (numbers come from the code output only).

    uv run --no-project python sensitivity_table.py            # prints and writes results/data/sensitivity/tables.md
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent / "results" / "data" / "sensitivity"
C1, C2 = "C1-central-serialization", "C2-distributed-lock"
INT = "INT-H100-B200"


def f(x, nd=3):
    return "—" if x is None else (f"{x:.{nd}f}" if isinstance(x, float) else str(x))


def grid_matrix(S, system, key, cands=(C1, C2), nd=3, title=""):
    etas, bgs = S["meta"]["etas"], S["meta"]["backgrounds"]
    lines = [f"**{title}** ({system}; C1 / C2)", "", "| eta_cxl \\ bg | " + " | ".join(str(b) for b in bgs) + " |", "|---|" + "---|" * len(bgs)]
    for e in etas:
        cells = []
        for b in bgs:
            m = S["configs"]["eta_cxl_bg"][f"eta{e}_bg{b}"][system]["candidates"]
            cells.append(" / ".join(f(m[c][key], nd) for c in cands))
        lines.append(f"| {e} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main_row(S, system):
    m = S["main"][system]["candidates"]
    return {c: m[c] for c in m}


def tables(S):
    out = ["# DP4 sensitivity tables (generated by sensitivity_table.py; simulation output, Evidence [B+C])", ""]
    out.append(f"Main reference (eta_cxl 0.5, bg 0.85): integrated QA1 ratio C1 {f(S['main'][INT]['candidates'][C1]['qa1_ratio'])}, "
               f"C2 {f(S['main'][INT]['candidates'][C2]['qa1_ratio'])}; effective-bandwidth parity eta_cxl = {f(S['meta']['eta_bw_parity'])} "
               f"(candidate node CXL bandwidth = Baseline RDMA bandwidth).")
    if "control_check" in S:
        out += ["", "Control (grid cell eta 0.5 / bg 0.85 vs main): " + ", ".join(f"{k}: {'match' if v['match'] else 'MISMATCH'} (max diff {v['max_abs_diff']:.2e})" for k, v in S["control_check"].items())]
    if "eta_cxl_bg" in S["configs"] and "eta0.5_bg0.85" in S["configs"]["eta_cxl_bg"]:
        for system in (INT, "SYS-H100", "SYS-B200"):
            out += ["", grid_matrix(S, system, "qa1_ratio", title="QA1 geometric-mean ratio vs Baseline (>= 1.00 reaches the Baseline)")]
        out += ["", grid_matrix(S, INT, "qa3_multiplier", title="QA3 saving multiplier at the Baseline-peak load (>= 1.00 reaches the Baseline)")]
        out += ["", grid_matrix(S, INT, "qa3_load1_multiplier", title="QA3 saving multiplier at load x1.0")]
        out += ["", grid_matrix(S, INT, "tail_ttft_worse_common", nd=0, title="TTFT P99 worse pairs at the common load (of 6; 0 reaches the Baseline)")]
        out += ["", grid_matrix(S, INT, "tail_ttft_worst_ratio_common", nd=2, title="Worst TTFT P99 pair ratio (candidate / Baseline) at the common load")]
        out += ["", grid_matrix(S, INT, "ttft_p99_ms_load1", nd=0, title="TTFT P99 geomean at load x1.0 (ms)")]
        b = S["configs"]["eta_cxl_bg"]
        e0 = S["meta"]["etas"][0]
        base = " / ".join("%.0f" % b["eta%s_bg%s" % (e0, bg)][INT]["candidates"]["Baseline-RDMA"]["ttft_p99_ms_load1"] for bg in S["meta"]["backgrounds"])
        out.append(f"\nBaseline TTFT P99 at load x1.0 for bg {S['meta']['backgrounds']}: {base} ms (Baseline does not depend on eta_cxl).")
    if "break_even" in S:
        out += ["", "## Break-even over eta_cxl (integrated; where the candidate reaches the Baseline)", "",
                "| criterion | candidate | bg | status | eta_cxl* | best value in grid (at eta) | provenance of eta_cxl* |", "|---|---|---|---|---|---|---|"]
        for crit in ("qa1_ratio_ge_1", "qa1_ratio_parity", "qa3_multiplier_ge_1", "qa3_multiplier_parity", "qa3_load1_multiplier_ge_1", "ttft_worse_pairs_common_eq_0", "ttft_worse_pairs_own_eq_0"):
            for c in (C1, C2):
                for bg, d in S["break_even"][INT][c].items():
                    r = d[crit]
                    out.append(f"| {crit} | {c.split('-')[0]} | {bg[2:]} | {r['status']} | {f(r['x'])} | {f(r['best'])} ({r['at']}) | {r['eta_cxl_provenance_note']} |")
    if "break_even_bg" in S:
        out += ["", "## Break-even over the background level at fixed eta_cxl (integrated; parity = ratio >= 0.99; background is an ASSUMED scenario constant)", "",
                "| criterion | candidate | eta_cxl | status | largest bg reaching Baseline | best value (at bg) |", "|---|---|---|---|---|---|"]
        for crit in ("qa1_ratio_parity", "qa3_multiplier_parity", "ttft_worse_pairs_common_eq_0"):
            for c in (C1, C2):
                for e, d in S["break_even_bg"][INT][c].items():
                    r = d[crit]
                    out.append(f"| {crit} | {c.split('-')[0]} | {e[3:]} | {r['status']} | {f(r['x'])} | {f(r['best'])} ({r['at']}) |")
    out += ["", "## Single-parameter sweeps (integrated; C1 / C2)", "", "| group | value | QA1 ratio | QA3 multiplier | TTFT worse pairs (common) |", "|---|---|---|---|---|"]
    for g, cs in S["one_param_sweeps"].items():
        for lab in cs[C1]:
            a, b = cs[C1][lab], cs[C2][lab]
            out.append(f"| {g} | {lab} | {f(a['qa1_ratio'])} / {f(b['qa1_ratio'])} | {f(a['qa3_multiplier'])} / {f(b['qa3_multiplier'])} | {a['ttft_worse_common']} / {b['ttft_worse_common']} |")
    out += ["", "## Control-plane sweeps on the DP4-specific rows (non-failure rows x 2 systems; failure rows differ by construction and are listed in summary.json)", "",
            "| group | value | max abs deviation of C2/C1 goodput | DP4 QA1 ratio C1 / C2 | DP4 comparison_valid rows |", "|---|---|---|---|---|"]
    for g, cfgs in S["configs"].items():
        for lab, v in cfgs.items():
            if INT in v and "c1_vs_c2_dp4_max_abs_dev" in v[INT]:
                x = v[INT]
                out.append(f"| {g} | {lab} | {x['c1_vs_c2_dp4_max_abs_dev']:.4f} | {f(x['dp4_qa1_ratio'][C1])} / {f(x['dp4_qa1_ratio'][C2])} | {x['fit_dp4']['comparison_valid']} |")
    out += ["", "## Star boundaries x0.9 / x1.0 / x1.1 (main result re-scored; stars as QA1/QA2/QA3)", "", "| system | scale | Baseline | C1 | C2 |", "|---|---|---|---|---|"]
    for sysname, d in S["star_boundary_pm10"].items():
        for sc in ("0.9", "1.0", "1.1"):
            cells = [f"{d[sc][c]['qa1']}/{d[sc][c]['qa2']}/{d[sc][c]['qa3']} (sum {d[sc][c]['total']})" for c in ("Baseline-RDMA", C1, C2)]
            out.append(f"| {sysname} | {sc} | " + " | ".join(cells) + " |")
    return "\n".join(out) + "\n"


def main():
    S = json.loads((ROOT / "summary.json").read_text())
    text = tables(S)
    (ROOT / "tables.md").write_text(text)
    sys.stdout.write(text)


if __name__ == "__main__":
    main()
